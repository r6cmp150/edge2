// scripts/capture-live-columns.mjs — 2026-11-06. Writes db/live-columns.json FROM A CAPTURE of the live database, never by
// hand: every future deploy's safety rests on that file (tests/live-columns.test.js), and a hand-edited literal in it
// would be db/037's failure again (a guard literal that didn't match the live database), with a deploy outage as the
// consequence instead of an aborted transaction.
//
// The capture is the one cell db/inspect-public-schema-read-only.sql returns, run by Roman in the Supabase SQL editor and
// saved as a JSON file (kept out of git: live-schema-*.json). This records the query's hash, the capture file's hash,
// its row counts, and a hash of the tables it writes, which the test recomputes; and the migrations the capture is
// declared to reflect, which the test checks against the capture itself and against db/.
//
//   node scripts/capture-live-columns.mjs <capture.json> --captured <YYYY-MM-DD> --by "<who ran it>" \
//        --applied <n,n,..> --not-applied <n,n,..>
//
// --applied / --not-applied: migration numbers. Every numbered migration in db/ must be in exactly one; the test fails
// otherwise, and fails if a not-applied migration's columns are in the capture, or an applied one's are missing.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
// v1 returns an array of tables; v2 an object { query: 'inspect-public-schema-v2', tables, functions, default_acls }.
const QUERIES = { v1: 'db/inspect-public-schema-read-only.sql', v2: 'db/inspect-public-schema-v2-read-only.sql' };
const sha = s => createHash('sha256').update(s).digest('hex');

const arg = n => { const i = process.argv.indexOf(n); return i < 0 ? null : process.argv[i + 1]; };
const file = process.argv[2];
const captured = arg('--captured'), by = arg('--by');
const nums = s => (s ? s.split(',').map(x => x.trim()).filter(Boolean).map(Number) : []);
const applied = nums(arg('--applied')), notApplied = nums(arg('--not-applied'));
if (!file || !captured || !by || !applied.length) {
  console.error('usage: node scripts/capture-live-columns.mjs <capture.json> --captured <YYYY-MM-DD> --by "<who>" --applied <n,..> --not-applied <n,..>');
  process.exit(2);
}

const raw = readFileSync(file);
const parsed = JSON.parse(raw.toString('utf8'));
const version = Array.isArray(parsed) ? 'v1' : parsed && parsed.query === 'inspect-public-schema-v2' ? 'v2' : null;
const capture = version === 'v1' ? parsed : version === 'v2' ? parsed.tables : null;
if (!capture || !Array.isArray(capture) || !capture.every(t => typeof t.table === 'string' && Array.isArray(t.columns))
    || (version === 'v2' && !Array.isArray(parsed.functions))) {
  console.error(`${file}: not the output of either inspect query (v1: an array of { table, columns }; v2: { query, tables, functions, default_acls })`);
  process.exit(1);
}
const QUERY = QUERIES[version];
const tables = {};
for (const t of [...capture].sort((a, b) => a.table.localeCompare(b.table))) tables[t.table] = t.columns.map(c => c.name).sort();
// functions by name; null when the capture didn't read them (v1), which is "unknown", never "none"
const functions = version === 'v2' ? [...new Set(parsed.functions.map(f => f.name))].sort() : null;
const columns = Object.values(tables).reduce((n, c) => n + c.length, 0);

const out = {
  _rule: 'GENERATED by scripts/capture-live-columns.mjs from a capture of the live database; never edit by hand. A column goes in this file only once a capture shows it. tests/live-columns.test.js recomputes every hash and count below.',
  _source: {
    query: QUERY,
    query_sha256: sha(readFileSync(path.join(REPO, QUERY), 'utf8').replace(/\r\n/g, '\n')),
    captured,
    captured_by: by,
    capture_file: path.basename(file),
    capture_sha256: sha(raw),
    tables: Object.keys(tables).length,
    columns,
    tables_sha256: sha(JSON.stringify(tables)),
    functions_sha256: sha(JSON.stringify(functions)),
  },
  _migrations: {
    highest_applied: Math.max(...applied),
    applied: [...applied].sort((a, b) => a - b),
    not_applied: [...notApplied].sort((a, b) => a - b),
  },
  functions,
  tables,
};
writeFileSync(path.join(REPO, 'db/live-columns.json'), JSON.stringify(out, null, 2) + '\n');
console.log(`db/live-columns.json: ${out._source.tables} tables, ${columns} columns, from ${path.basename(file)} (sha256 ${out._source.capture_sha256.slice(0, 16)}), highest applied db/${String(out._migrations.highest_applied).padStart(3, '0')}`);
