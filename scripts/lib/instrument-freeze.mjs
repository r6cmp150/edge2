// scripts/lib/instrument-freeze.mjs -- the forward test's frozen instrument (STATUS, "THE INSTRUMENT IS FROZEN",
// declared 2026-11-25): split a source into its top-level declarations, hash what can reach a measured quantity, and
// find every declaration the frozen roots can reach, so nothing on the path can be left unclassified.
import { createHash } from 'node:crypto';

// Top-level declarations: a chunk starts at a column-0 `function`, `async function`, `const`, `let`, `var` or `class`
// and runs to the line before the next one. Comments between declarations belong to the chunk above.
export function chunks(src) {
  const lines = src.split('\n'), out = [];
  const head = /^(?:async\s+function\s*\*?\s*([A-Za-z_$][\w$]*)|function\s*\*?\s*([A-Za-z_$][\w$]*)|(?:const|let|var)\s+([A-Za-z_$][\w$]*)|class\s+([A-Za-z_$][\w$]*))/;
  let cur = null;
  lines.forEach((l, i) => {
    const m = l.match(head);
    if (m) { if (cur) out.push(cur); cur = { name: m[1] || m[2] || m[3] || m[4], line: i + 1, text: l }; }
    else if (cur) cur.text += '\n' + l;
  });
  if (cur) out.push(cur);
  return out;
}
// what the hash sees: no comments, no blank lines, whitespace collapsed. A comment or re-indent is not a change of
// instrument; any change to code is. ("//" after ':' is a URL, not a comment.)
export function normalize(text) {
  return text.replace(/\/\*[\s\S]*?\*\//g, ' ').split('\n').map(l => l.replace(/(^|[^:\\'"`])\/\/.*$/, '$1')).join('\n').replace(/\s+/g, ' ').trim();
}
export const sha256 = s => createHash('sha256').update(s).digest('hex');
export const hashChunk = c => sha256(normalize(c.text));
export const hashFile = src => sha256(normalize(src));

// every top-level declaration of `src` reachable from `roots` by name, NOT passing through those declared OUT
// (an OUT declaration's own references are not followed: it was declared unable to reach a measured quantity).
export function closure(src, roots, outNames = []) {
  const cs = chunks(src), byName = new Map();
  for (const c of cs) if (!byName.has(c.name)) byName.set(c.name, c);
  const out = new Set(outNames), seen = new Set(), queue = [...roots];
  while (queue.length) {
    const n = queue.shift();
    if (seen.has(n) || !byName.has(n)) continue;
    seen.add(n);
    if (out.has(n)) continue;
    // Strings are NOT stripped: an apostrophe inside a template literal ("Roman's") made a string-stripper swallow
    // real call sites (found 2026-11-25: confirmMarkSold's call to recordSaleThenRemovePosition vanished). A name
    // mentioned only in a string is pulled in, which over-includes, the safe direction for a freeze.
    const body = normalize(byName.get(n).text);
    for (const id of new Set(body.match(/[A-Za-z_$][\w$]*/g) || [])) if (id !== n && byName.has(id) && !seen.has(id)) queue.push(id);
  }
  return [...seen];
}
// duplicate top-level names would make a by-name hash ambiguous
export function duplicates(src) {
  const c = {}; for (const x of chunks(src)) c[x.name] = (c[x.name] || 0) + 1;
  return Object.entries(c).filter(([, n]) => n > 1).map(([k]) => k);
}

// ---- the manifest and the check (2026-11-25). `read(path)` returns a file's text or null, so the same check runs on
// the working tree or on any commit (git show).
export const stripStamps = html => html.replace(/\?v=\d+/g, '');
export const SCANNED_DIRS = ['core', 'engines', 'shell'];
function fileHash(path, text) { return path === 'index.html' ? hashFile(stripStamps(text)) : path.endsWith('.json') ? sha256(text) : hashFile(text); }
export function frozenDeclarations(appSrc, spec) {
  const outNames = Object.values(spec.app_js.out).flatMap(g => g.names);
  return closure(appSrc, spec.app_js.roots, outNames).filter(n => !outNames.includes(n)).sort();
}
// the manifest: the frozen list, enumerated, with each item's hash at the baseline, and the frozen settings' values
export function buildManifest(read, spec, settingsRow, baselineCommit) {
  const app = read('app.js'), byName = new Map(chunks(app).map(c => [c.name, c]));
  const decl = frozenDeclarations(app, spec);
  return {
    declared: spec.declared, start_line: spec.start_line, start_line_commit: spec.start_line_commit, baseline_commit: baselineCommit,
    note: 'GENERATED by scripts/check-instrument-freeze.mjs --write-manifest from data/forward-test/instrument-freeze-spec.json. The detector reads THIS list. Regenerating it is a restart of the forward test, never a fix.',
    files: Object.fromEntries(Object.keys(spec.files.frozen).sort().map(p => [p, fileHash(p, read(p))])),
    app_js: Object.fromEntries(decl.map(n => [n, hashChunk(byName.get(n))])),
    settings: Object.fromEntries(spec.settings.frozen.map(k => [k, settingsRow[k]])),
  };
}
// the check: every frozen item against its baseline hash; every file and declaration classified; the settings values
export function checkFreeze({ read, list, manifest, spec, settingsRow }) {
  const changed = [], unclassified = [];
  for (const [p, h] of Object.entries(manifest.files)) { const t = read(p); if (t == null) changed.push(`${p} (missing)`); else if (fileHash(p, t) !== h) changed.push(p); }
  const app = read('app.js'), byName = new Map(chunks(app).map(c => [c.name, c]));
  for (const [n, h] of Object.entries(manifest.app_js)) { const c = byName.get(n); if (!c) changed.push(`app.js ${n} (missing)`); else if (hashChunk(c) !== h) changed.push(`app.js ${n}`); }
  const outNames = new Set(Object.values(spec.app_js.out).flatMap(g => g.names));
  for (const c of chunks(app)) if (!(c.name in manifest.app_js) && !outNames.has(c.name)) unclassified.push(`app.js ${c.name}`);
  const known = new Set([...Object.keys(spec.files.frozen), ...Object.keys(spec.files.partial), ...Object.keys(spec.files.out)]);
  for (const p of list()) if (!known.has(p)) unclassified.push(p);
  for (const [k, v] of Object.entries(manifest.settings)) if (JSON.stringify(settingsRow?.[k]) !== JSON.stringify(v)) changed.push(`setting ${k}: ${JSON.stringify(v)} -> ${JSON.stringify(settingsRow?.[k])}`);
  return { changed, unclassified, intact: !changed.length && !unclassified.length };
}
